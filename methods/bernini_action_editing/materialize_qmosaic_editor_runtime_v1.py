def _verify_runtime_signature(
    receipt: Mapping[str, Any],
    *,
    public_key_path: str | Path,
    expected_public_key_file_sha256: str,
) -> None:
    try:
        from cryptography.exceptions import InvalidSignature
        from cryptography.hazmat.primitives import serialization
        from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PublicKey
    except ImportError as error:  # pragma: no cover
        raise QmosaicRuntimeMaterializationError(
            "cryptography Ed25519 support is required"
        ) from error
    public_path = _plain_file(public_key_path, label="authority public key")
    observed_key_sha = file_sha256(public_path)
    if observed_key_sha != _sha256(
        expected_public_key_file_sha256,
        label="authority public key file SHA-256",
    ):
        raise QmosaicRuntimeMaterializationError(
            "authority public key bytes changed"
        )
    value = dict(receipt)
    encoded = value.pop("authority_signature_ed25519_base64", None)
    unsigned_with_digest = dict(value)
    declared = value.pop("receipt_digest", None)
    if (
        receipt.get("schema_version") != RUNTIME_INPUT_SCHEMA
        or receipt.get("authority_signature_scheme") != SIGNATURE_SCHEME
        or receipt.get("authority_public_key_sha256") != observed_key_sha
        or declared != object_sha256(value)
        or not isinstance(encoded, str)
    ):
        raise QmosaicRuntimeMaterializationError(
            "signed runtime receipt scalar/seal differs"
        )
    try:
        signature = base64.b64decode(encoded.encode("ascii"), validate=True)
        public = serialization.load_pem_public_key(public_path.read_bytes())
        if not isinstance(public, Ed25519PublicKey) or len(signature) != 64:
            raise QmosaicRuntimeMaterializationError(
                "runtime receipt Ed25519 key/signature differs"
            )
        public.verify(signature, canonical_json_bytes(unsigned_with_digest))
    except QmosaicRuntimeMaterializationError:
        raise
    except (InvalidSignature, ValueError, UnicodeError) as error:
        raise QmosaicRuntimeMaterializationError(
            "runtime receipt Ed25519 verification failed"
        ) from error


