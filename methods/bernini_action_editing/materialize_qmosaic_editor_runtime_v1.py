class QmosaicRuntimeMaterializationError(RuntimeError):
    """Raised before an incomplete or unauthenticated packet can publish."""


def canonical_json_bytes(value: Any) -> bytes:
    try:
        return json.dumps(
            value,
            sort_keys=True,
            separators=(",", ":"),
            ensure_ascii=True,
            allow_nan=False,
        ).encode("ascii")
    except (TypeError, ValueError, UnicodeEncodeError) as error:
        raise QmosaicRuntimeMaterializationError(
            "value is not canonical finite ASCII JSON"
        ) from error


def object_sha256(value: Any) -> str:
    return hashlib.sha256(canonical_json_bytes(value)).hexdigest()


def _plain_provenance_tree(value: Any, *, label: str) -> Any:
    """Convert only the closed receipt container types to plain JSON values.

    Runtime provenance helpers intentionally return ``MappingProxyType`` to
    prevent mutation.  JSON sealing must not teach the global canonical
    encoder to coerce arbitrary objects, so this construction boundary admits
    only exact dict/mappingproxy, list/tuple, and scalar JSON types.  It also
    rejects cycles and non-string object keys before a digest is computed.
    """

    active: set[int] = set()

    def convert(item: Any, path: str) -> Any:
        if item is None or type(item) in (bool, int, str):
            return item
        if type(item) is float:
            if not math.isfinite(item):
                raise QmosaicRuntimeMaterializationError(
                    f"{label} contains non-finite scalar at {path}"
                )
            return item
        if type(item) is dict or type(item) is MappingProxyType:
            identity = id(item)
            if identity in active:
                raise QmosaicRuntimeMaterializationError(
                    f"{label} contains a container cycle at {path}"
                )
            active.add(identity)
            try:
                output: dict[str, Any] = {}
                for key, child in item.items():
                    if type(key) is not str:
                        raise QmosaicRuntimeMaterializationError(
                            f"{label} contains a non-string key at {path}"
                        )
                    output[key] = convert(child, f"{path}.{key}")
                return output
            finally:
                active.remove(identity)
        if type(item) is list or type(item) is tuple:
            identity = id(item)
            if identity in active:
                raise QmosaicRuntimeMaterializationError(
                    f"{label} contains a container cycle at {path}"
                )
            active.add(identity)
            try:
                return [
                    convert(child, f"{path}[{index}]")
                    for index, child in enumerate(item)
                ]
            finally:
                active.remove(identity)
        raise QmosaicRuntimeMaterializationError(
            f"{label} contains unsupported provenance type at {path}: "
            f"{type(item).__module__}.{type(item).__qualname__}"
        )

    plain = convert(value, "$")
    canonical_json_bytes(plain)
    return plain


def _seal_text_encoder_receipt(unsigned: Mapping[str, Any]) -> Mapping[str, Any]:
    """Seal the exact T5 receipt after strict immutable-to-plain conversion."""

    if type(unsigned) is not dict or set(unsigned) != _TEXT_ENCODER_UNSIGNED_FIELDS:
        raise QmosaicRuntimeMaterializationError(
            "T5 receipt construction field closure differs"
        )
    plain = _plain_provenance_tree(unsigned, label="T5 receipt provenance")
    if (
        type(plain) is not dict
        or plain.get("schema_version") != "qmosaic-pinned-umt5-receipt-v1"
        or plain.get("all_conditions_rank0_broadcast_and_world4_exact") is not True
    ):
        raise QmosaicRuntimeMaterializationError(
            "T5 receipt construction semantics differ"
        )
    return {**plain, "digest": object_sha256(plain)}


def _sha256(value: Any, *, label: str) -> str:
    if not isinstance(value, str) or _SHA256_RE.fullmatch(value) is None:
        raise QmosaicRuntimeMaterializationError(
            f"{label} must be lowercase SHA-256"
        )
    return value


def _sha1(value: Any, *, label: str) -> str:
    if not isinstance(value, str) or _SHA1_RE.fullmatch(value) is None:
        raise QmosaicRuntimeMaterializationError(
            f"{label} must be lowercase 40-hex Git identity"
        )
    return value


def _sealed_receipt_digest(
    receipt: Mapping[str, Any], *, schema_version: str, label: str
) -> str:
    if not isinstance(receipt, Mapping):
        raise QmosaicRuntimeMaterializationError(f"{label} must be a mapping")
    value = dict(receipt)
    declared = value.pop("digest", None)
    if (
        receipt.get("schema_version") != schema_version
        or declared != object_sha256(value)
    ):
        raise QmosaicRuntimeMaterializationError(
            f"{label} digest/schema differs"
        )
    return _sha256(declared, label=f"{label} digest")


def _plain_file(value: str | Path, *, label: str) -> Path:
    requested = Path(value)
    if not requested.is_absolute() or requested.is_symlink():
        raise QmosaicRuntimeMaterializationError(
            f"{label} must be an absolute non-symlink file"
        )
    resolved = requested.resolve(strict=True)
    if resolved != requested or not resolved.is_file() or resolved.is_symlink():
        raise QmosaicRuntimeMaterializationError(
            f"{label} must be a canonical plain file"
        )
    return resolved


def _plain_directory(value: str | Path, *, label: str) -> Path:
    requested = Path(value)
    if not requested.is_absolute() or requested.is_symlink():
        raise QmosaicRuntimeMaterializationError(
            f"{label} must be an absolute non-symlink directory"
        )
    resolved = requested.resolve(strict=True)
    if resolved != requested or not resolved.is_dir() or resolved.is_symlink():
        raise QmosaicRuntimeMaterializationError(
            f"{label} must be a canonical plain directory"
        )
    return resolved


def file_sha256(value: str | Path) -> str:
    path = _plain_file(value, label="hashed artifact")
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _implementation_source_file(value: Any, *, label: str) -> Path:
    """Resolve the actual Python implementation file for a live object."""

    module_name = getattr(value, "__module__", None)
    if module_name is None:
        module_name = getattr(type(value), "__module__", None)
    module = sys.modules.get(str(module_name))
    raw_path = getattr(module, "__file__", None)
    if not isinstance(raw_path, str) or not raw_path:
        raise QmosaicRuntimeMaterializationError(
            f"{label} implementation module has no source file"
        )
    return _plain_file(Path(raw_path).resolve(), label=f"{label} implementation")


def _validate_materializer_archive_member(
    archive: str | Path, *, expected_file_sha256: str
) -> str:
    """Bind executing materializer bytes to their exact Git-archive member."""

    path = _plain_file(archive, label="method source archive")
    expected = _sha256(
        expected_file_sha256, label="materializer archive member SHA-256"
    )
    try:
        with tarfile.open(path, "r:*") as handle:
            matches = [
                member
                for member in handle.getmembers()
                if member.name == MATERIALIZER_ARCHIVE_MEMBER
            ]
            if len(matches) != 1 or not matches[0].isfile():
                raise QmosaicRuntimeMaterializationError(
                    "materializer archive member closure differs"
                )
            opened = handle.extractfile(matches[0])
            if opened is None:
                raise QmosaicRuntimeMaterializationError(
                    "materializer archive member cannot be opened"
                )
            observed = hashlib.sha256(opened.read()).hexdigest()
    except QmosaicRuntimeMaterializationError:
        raise
    except (tarfile.TarError, OSError) as error:
        raise QmosaicRuntimeMaterializationError(
            "materializer archive member cannot be authenticated"
        ) from error
    if observed != expected:
        raise QmosaicRuntimeMaterializationError(
            "executing materializer differs from source archive member"
        )
    return observed


def _build_runtime_code_receipt(
    role_paths: Mapping[str, str | Path],
) -> Mapping[str, Any]:
    """Hash the exact method/model-library code used by materialization."""

    if not isinstance(role_paths, Mapping) or tuple(role_paths) != RUNTIME_CODE_ROLES:
        raise QmosaicRuntimeMaterializationError(
            "runtime code role/order closure differs"
        )
    rows = []
    for role in RUNTIME_CODE_ROLES:
        path = _plain_file(role_paths[role], label=f"runtime code {role}")
        rows.append(
            {
                "role": role,
                "path": str(path),
                "file_sha256": file_sha256(path),
            }
        )
    value = {
        "schema_version": "qmosaic-runtime-code-closure-v1",
        "role_order": list(RUNTIME_CODE_ROLES),
        "file_count": len(rows),
        "files": rows,
        "all_files_hashed_from_canonical_plain_paths": True,
    }
    return MappingProxyType({**value, "digest": object_sha256(value)})


def _validate_runtime_code_receipt(
    receipt: Mapping[str, Any],
    *,
    expected_materializer_path: Optional[str | Path] = None,
) -> str:
    """Rehash every code row; a recomputed opaque digest is not provenance."""

    if not isinstance(receipt, Mapping):
        raise QmosaicRuntimeMaterializationError(
            "runtime code receipt must be a mapping"
        )
    value = dict(receipt)
    declared = value.pop("digest", None)
    rows = value.get("files")
    if (
        set(receipt)
        != {
            "schema_version",
            "role_order",
            "file_count",
            "files",
            "all_files_hashed_from_canonical_plain_paths",
            "digest",
        }
        or receipt.get("schema_version") != "qmosaic-runtime-code-closure-v1"
        or receipt.get("role_order") != list(RUNTIME_CODE_ROLES)
        or receipt.get("file_count") != len(RUNTIME_CODE_ROLES)
        or receipt.get("all_files_hashed_from_canonical_plain_paths") is not True
        or not isinstance(rows, list)
        or len(rows) != len(RUNTIME_CODE_ROLES)
        or declared != object_sha256(value)
    ):
        raise QmosaicRuntimeMaterializationError(
            "runtime code receipt seal/closure differs"
        )
    for role, row in zip(RUNTIME_CODE_ROLES, rows):
        if (
            not isinstance(row, Mapping)
            or set(row) != {"role", "path", "file_sha256"}
            or row.get("role") != role
        ):
            raise QmosaicRuntimeMaterializationError(
                f"runtime code row differs for {role}"
            )
        path = _plain_file(row.get("path"), label=f"runtime code {role}")
        observed = file_sha256(path)
        if observed != _sha256(
            row.get("file_sha256"), label=f"runtime code {role} SHA-256"
        ):
            raise QmosaicRuntimeMaterializationError(
                f"runtime code bytes changed for {role}"
            )
        if (
            role == "qmosaic_materializer"
            and expected_materializer_path is not None
            and path
            != _plain_file(
                expected_materializer_path,
                label="expected executing materializer source",
            )
        ):
            raise QmosaicRuntimeMaterializationError(
                "runtime code materializer path differs from executing file"
            )
    return _sha256(declared, label="runtime code closure digest")


def _reject_duplicate_pairs(pairs: Sequence[tuple[str, Any]]) -> dict[str, Any]:
    result: dict[str, Any] = {}
    for key, value in pairs:
        if key in result:
            raise QmosaicRuntimeMaterializationError(
                f"JSON contains duplicate key {key!r}"
            )
        result[key] = value
    return result


def _strict_json_file(
    value: str | Path, *, expected_sha256: str, label: str
) -> tuple[dict[str, Any], Path, str]:
    path = _plain_file(value, label=label)
    observed = file_sha256(path)
    if observed != _sha256(expected_sha256, label=f"{label} file SHA-256"):
        raise QmosaicRuntimeMaterializationError(f"{label} bytes changed")
    raw = path.read_bytes()
    try:
        decoded = json.loads(
            raw.decode("ascii"),
            object_pairs_hook=_reject_duplicate_pairs,
            parse_constant=lambda token: (_ for _ in ()).throw(
                QmosaicRuntimeMaterializationError(
                    f"{label} contains non-finite number {token}"
                )
            ),
        )
    except (OSError, UnicodeError, json.JSONDecodeError) as error:
        raise QmosaicRuntimeMaterializationError(
            f"{label} is not strict ASCII JSON"
        ) from error
    if (
        not isinstance(decoded, dict)
        or raw != canonical_json_bytes(decoded) + b"\n"
    ):
        raise QmosaicRuntimeMaterializationError(
            f"{label} is not canonical create-only JSON"
        )
    return decoded, path, observed


def tensor_sha256(value: Any, *, label: str) -> str:
    """Use the exact tensor digest consumed by the Q-MOSAIC VJP core."""

    try:
        import torch
    except ImportError as error:  # pragma: no cover - AUH dependency
        raise QmosaicRuntimeMaterializationError("PyTorch is required") from error
    if (
        not isinstance(value, torch.Tensor)
        or value.device.type == "meta"
        or not bool(torch.isfinite(value).all().item())
    ):
        raise QmosaicRuntimeMaterializationError(
            f"{label} must be a finite materialized tensor"
        )
    owned = value.detach().to(device="cpu").contiguous().clone()
    payload = io.BytesIO()
    storage = owned.storage()
    untyped = (
        storage._untyped()
        if callable(getattr(storage, "_untyped", None))
        else owned.untyped_storage()
    )
    untyped._write_file(payload, False, False, 1)
    raw = payload.getvalue()
    expected = int(owned.numel()) * int(owned.element_size())
    if len(raw) != expected:
        raise QmosaicRuntimeMaterializationError(
            f"{label} owned storage closure differs"
        )
    header = canonical_json_bytes(
        {
            "dtype": str(owned.dtype),
            "shape": [int(item) for item in owned.shape],
            "numel": int(owned.numel()),
        }
    )
    return hashlib.sha256(header + b"\x00" + raw).hexdigest()


def _module_metadata_receipt(module: Any, *, component: str) -> Mapping[str, Any]:
    """Bind the loaded class and full parameter/buffer layout.

    Parameter bytes are already authenticated by the full checkpoint content
    manifest.  This receipt binds how those bytes were instantiated without
    copying a multi-billion-parameter model through CPU solely for a duplicate
    hash.
    """

    rows: list[dict[str, Any]] = []
    seen: set[tuple[str, str]] = set()
    trainable_tensors = 0
    trainable_elements = 0
    for kind, iterator in (
        ("parameter", module.named_parameters()),
        ("buffer", module.named_buffers()),
    ):
        for name, tensor in iterator:
            identity = (kind, name)
            if identity in seen:
                raise QmosaicRuntimeMaterializationError(
                    f"{component} has duplicate state entry"
                )
            seen.add(identity)
            trainable = bool(getattr(tensor, "requires_grad", False))
            if kind == "parameter" and trainable:
                trainable_tensors += 1
                trainable_elements += int(tensor.numel())
            rows.append(
                {
                    "kind": kind,
                    "name": name,
                    "shape": [int(item) for item in tensor.shape],
                    "dtype": str(tensor.dtype),
                    "numel": int(tensor.numel()),
                    "requires_grad": trainable,
                }
            )
    rows.sort(key=lambda row: (row["kind"], row["name"]))
    config = getattr(module, "config", None)
    if callable(getattr(config, "to_dict", None)):
        config_digest = object_sha256(config.to_dict())
    else:
        config_digest = object_sha256(
            {
                "config_class": None
                if config is None
                else f"{type(config).__module__}.{type(config).__qualname__}"
            }
        )
    value = {
        "schema_version": "qmosaic-loaded-component-metadata-v1",
        "component": component,
        "class": f"{type(module).__module__}.{type(module).__qualname__}",
        "config_digest": config_digest,
        "state_layout_digest": object_sha256(rows),
        "state_entry_count": len(rows),
        "trainable_parameter_tensors": trainable_tensors,
        "trainable_parameter_elements": trainable_elements,
        "all_parameters_frozen": trainable_tensors == 0,
    }
    if trainable_tensors:
        raise QmosaicRuntimeMaterializationError(
            f"{component} contains trainable parameters"
        )
    return MappingProxyType({**value, "digest": object_sha256(value)})


def _official_cpu_gaussian(shape: Sequence[int], *, query_seed: int) -> Any:
    try:
        import torch
    except ImportError as error:  # pragma: no cover
        raise QmosaicRuntimeMaterializationError("PyTorch is required") from error
    dims = tuple(int(item) for item in shape)
    if (
        len(dims) != 5
        or dims[:3] != (1, 16, LATENT_PHASES)
        or any(item <= 0 for item in dims)
        or type(query_seed) is not int
        or not 0 <= query_seed < 2**63
    ):
        raise QmosaicRuntimeMaterializationError(
            "official Gaussian shape/seed differs"
        )
    generator = torch.Generator(device="cpu")
    generator.manual_seed(query_seed)
    return torch.randn(dims, generator=generator, dtype=torch.float32).contiguous()


def _vendor_condition_bf16(value: Any, *, transformer: Any, label: str) -> Any:
    """Cast a signed FP32 condition only for the frozen Bernini BF16 call."""

    try:
        import torch
    except ImportError as error:  # pragma: no cover - production dependency
        raise QmosaicRuntimeMaterializationError(
            "Bernini condition casting requires PyTorch"
        ) from error
    patch_embedding = getattr(transformer, "patch_embedding", None)
    weight = getattr(patch_embedding, "weight", None)
    if (
        not isinstance(value, torch.Tensor)
        or value.dtype != torch.float32
        or value.requires_grad
        or value.grad_fn is not None
        or not isinstance(weight, torch.Tensor)
        or weight.dtype != torch.bfloat16
    ):
        raise QmosaicRuntimeMaterializationError(
            f"{label} signed FP32/Bernini BF16 boundary differs"
        )
    vendor = value.to(device=weight.device, dtype=weight.dtype).contiguous()
    if (
        vendor.dtype != torch.bfloat16
        or vendor.device != weight.device
        or vendor.requires_grad
        or vendor.grad_fn is not None
        or not bool(torch.isfinite(vendor).all().item())
    ):
        raise QmosaicRuntimeMaterializationError(
            f"{label} Bernini vendor condition cast differs"
        )
    return vendor


def _capture_live_exact40_schedule(
    scheduler: Any, *, schedule_contract: Any
) -> Mapping[str, Any]:
    """Bind the post-sample live UniPC timeline to the pinned exact40 table."""

    try:
        import torch
    except ImportError as error:  # pragma: no cover
        raise QmosaicRuntimeMaterializationError("PyTorch is required") from error
    static = dict(schedule_contract.native_unipc40_schedule_receipt())
    static_unsigned = dict(static)
    static_digest = static_unsigned.pop("digest", None)
    expected_timesteps = tuple(schedule_contract.NATIVE_UNIPC40_TIMESTEPS)
    expected_sigmas = tuple(schedule_contract.NATIVE_UNIPC40_SIGMAS)
    if (
        static_digest != object_sha256(static_unsigned)
        or static_digest != NATIVE_UNIPC40_SCHEDULE_DIGEST
        or tuple(static.get("timesteps", ())) != expected_timesteps
        or tuple(static.get("sigma_float64_hex", ()))
        != tuple(float(item).hex() for item in expected_sigmas)
        or expected_timesteps[NATIVE_SCHEDULE_INDEX] != NATIVE_TIMESTEP
        or float(expected_sigmas[NATIVE_SCHEDULE_INDEX]).hex()
        != float(NATIVE_SIGMA).hex()
    ):
        raise QmosaicRuntimeMaterializationError(
            "pinned native exact40 schedule receipt differs"
        )
    timesteps = getattr(scheduler, "timesteps", None)
    sigmas = getattr(scheduler, "sigmas", None)
    if (
        not isinstance(timesteps, torch.Tensor)
        or timesteps.device.type != "cpu"
        or timesteps.ndim != 1
        or int(timesteps.numel()) != NUM_INFERENCE_STEPS
        or not bool(torch.isfinite(timesteps).all().item())
        or not isinstance(sigmas, torch.Tensor)
        or sigmas.device.type != "cpu"
        or sigmas.dtype != torch.float32
        or sigmas.ndim != 1
        or int(sigmas.numel()) != NUM_INFERENCE_STEPS + 1
        or not bool(torch.isfinite(sigmas).all().item())
    ):
        raise QmosaicRuntimeMaterializationError(
            "live native exact40 scheduler tensor closure differs"
        )
    observed_timesteps = tuple(int(item.item()) for item in timesteps)
    if any(
        float(item.item()) != float(integer)
        for item, integer in zip(timesteps, observed_timesteps)
    ):
        raise QmosaicRuntimeMaterializationError(
            "live native exact40 timesteps are not exact integers"
        )
    observed_sigmas = tuple(float(item.item()) for item in sigmas[:40])
    if (
        observed_timesteps != expected_timesteps
        or observed_sigmas != expected_sigmas
        or float(sigmas[40].item()) != 0.0
    ):
        raise QmosaicRuntimeMaterializationError(
            "live native exact40 timesteps/sigmas differ from the pin"
        )
    value = {
        "schema_version": "qmosaic-live-native-unipc40-schedule-v1",
        "static_schedule_digest": static_digest,
        "observed_after_native_sample": True,
        "timesteps_device": timesteps.device.type,
        "timesteps_dtype": str(timesteps.dtype),
        "timesteps_tensor_sha256": tensor_sha256(
            timesteps, label="live native exact40 timesteps"
        ),
        "sigmas_device": sigmas.device.type,
        "sigmas_dtype": str(sigmas.dtype),
        "sigmas_tensor_sha256": tensor_sha256(
            sigmas, label="live native exact40 sigmas"
        ),
        "timesteps": list(observed_timesteps),
        "sigma_float64_hex": [float(item).hex() for item in observed_sigmas],
        "terminal_sigma_hex": float(sigmas[40].item()).hex(),
        "selected_coordinate": {
            "schedule_index": NATIVE_SCHEDULE_INDEX,
            "timestep": observed_timesteps[NATIVE_SCHEDULE_INDEX],
            "sigma_hex": float(observed_sigmas[NATIVE_SCHEDULE_INDEX]).hex(),
        },
        "exact40_matches_static_contract": True,
    }
    return MappingProxyType({**value, "digest": object_sha256(value)})


def _validate_endpoint_schedule_receipts(endpoint: Mapping[str, Any]) -> None:
    static = endpoint.get("exact40_schedule")
    live = endpoint.get("live_exact40_schedule")
    if not isinstance(static, Mapping) or not isinstance(live, Mapping):
        raise QmosaicRuntimeMaterializationError(
            "native endpoint schedule receipts are missing"
        )
    static_unsigned = dict(static)
    static_digest = static_unsigned.pop("digest", None)
    live_unsigned = dict(live)
    live_digest = live_unsigned.pop("digest", None)
    timesteps = static.get("timesteps")
    sigmas = static.get("sigma_float64_hex")
    selected = live.get("selected_coordinate")
    if (
        static_digest != NATIVE_UNIPC40_SCHEDULE_DIGEST
        or static_digest != object_sha256(static_unsigned)
        or static.get("num_inference_steps") != NUM_INFERENCE_STEPS
        or static.get("model_forward_count") != NUM_INFERENCE_STEPS
        or not isinstance(timesteps, list)
        or len(timesteps) != NUM_INFERENCE_STEPS
        or not isinstance(sigmas, list)
        or len(sigmas) != NUM_INFERENCE_STEPS
        or timesteps[NATIVE_SCHEDULE_INDEX] != NATIVE_TIMESTEP
        or sigmas[NATIVE_SCHEDULE_INDEX] != float(NATIVE_SIGMA).hex()
        or live.get("schema_version")
        != "qmosaic-live-native-unipc40-schedule-v1"
        or live_digest != object_sha256(live_unsigned)
        or live.get("static_schedule_digest") != static_digest
        or live.get("observed_after_native_sample") is not True
        or live.get("timesteps_device") != "cpu"
        or live.get("sigmas_device") != "cpu"
        or live.get("sigmas_dtype") != "torch.float32"
        or live.get("timesteps") != timesteps
        or live.get("sigma_float64_hex") != sigmas
        or live.get("terminal_sigma_hex") != float(0.0).hex()
        or live.get("exact40_matches_static_contract") is not True
        or selected
        != {
            "schedule_index": NATIVE_SCHEDULE_INDEX,
            "timestep": NATIVE_TIMESTEP,
            "sigma_hex": float(NATIVE_SIGMA).hex(),
        }
    ):
        raise QmosaicRuntimeMaterializationError(
            "native endpoint exact40 schedule provenance differs"
        )
    _sha256(live.get("timesteps_tensor_sha256"), label="live timesteps SHA-256")
    _sha256(live.get("sigmas_tensor_sha256"), label="live sigmas SHA-256")


