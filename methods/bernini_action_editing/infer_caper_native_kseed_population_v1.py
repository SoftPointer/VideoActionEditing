class CaperNativeKSeedPopulationError(RuntimeError):
    """Raised before an incomplete, filtered, or prematurely opened population ships."""


def _object_sha256(value: Any) -> str:
    payload = json.dumps(
        value,
        sort_keys=True,
        separators=(",", ":"),
        ensure_ascii=True,
        allow_nan=False,
    ).encode("ascii")
    return hashlib.sha256(payload).hexdigest()


def _sha256_text(value: str) -> str:
    return hashlib.sha256(value.encode("utf-8")).hexdigest()


def _file_sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _plain_json(value: str | Path, *, label: str) -> tuple[Path, Mapping[str, Any]]:
    requested = Path(value).expanduser()
    if not requested.is_absolute() or requested.is_symlink():
        raise CaperNativeKSeedPopulationError(f"{label} path differs")
    path = requested.resolve(strict=True)
    if path != requested or not path.is_file() or path.is_symlink():
        raise CaperNativeKSeedPopulationError(f"{label} must be a plain absolute file")
    try:
        payload = json.loads(path.read_text(encoding="utf-8"))
    except Exception as error:
        raise CaperNativeKSeedPopulationError(f"{label} is not valid JSON") from error
    if not isinstance(payload, Mapping):
        raise CaperNativeKSeedPopulationError(f"{label} root differs")
    return path, payload


