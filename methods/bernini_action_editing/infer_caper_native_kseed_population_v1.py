def _expected_cell_order(
    source_ids: Sequence[str], seeds: Sequence[int], *, phase: str
) -> list[str]:
    return [
        f"{phase}-{source_id}-s{seed}"
        for source_id in source_ids
        for seed in seeds
    ]


def _validate_population_design(registry: Mapping[str, Any]) -> None:
    population = registry.get("population_design")
    if (
        not isinstance(population, Mapping)
        or population.get("phase_order") != ["fit", "lockbox"]
        or population.get("default_launcher_phase") != "fit"
        or population.get(
            "fit_and_lockbox_never_aggregated_as_independent_training_targets"
        )
        is not True
        or population.get("all_registered_cells_must_materialize_before_phase_receipt")
        is not True
        or population.get("partial_population_scientific_claim_authorized") is not False
        or population.get("posthoc_seed_selection_authorized") is not False
    ):
        raise CaperNativeKSeedPopulationError("population root differs")
    for phase in ("fit", "lockbox"):
        row = population.get(phase)
        expected_sources = list(PHASE_SOURCE_IDS[phase])
        expected_seeds = list(PHASE_SEEDS[phase])
        expected_cells = list(PHASE_CELL_ORDER[phase])
        if (
            not isinstance(row, Mapping)
            or row.get("source_ids") != expected_sources
            or row.get("seeds") != expected_seeds
            or row.get("cell_order") != expected_cells
            or row.get("cell_order")
            != _expected_cell_order(expected_sources, expected_seeds, phase=phase)
            or row.get("cartesian_population_required") is not True
            or row.get("expected_cell_count") != len(expected_cells)
            or row.get("seed_filtering_or_best_of_k_authorized") is not False
        ):
            raise CaperNativeKSeedPopulationError(f"{phase} Cartesian population differs")
    lockbox = population["lockbox"]
    if (
        lockbox.get("explicit_second_stage_switch_required") is not True
        or lockbox.get("threshold_freeze_receipt_required") is not True
        or lockbox.get("lockbox_media_must_remain_unopened_before_freeze") is not True
    ):
        raise CaperNativeKSeedPopulationError("lockbox release boundary differs")


def _validate_sources(registry: Mapping[str, Any]) -> Mapping[str, Mapping[str, Any]]:
    rows = registry.get("sources")
    if not isinstance(rows, list) or len(rows) != 6:
        raise CaperNativeKSeedPopulationError("source registry differs")
    by_id: dict[str, Mapping[str, Any]] = {}
    for row in rows:
        if not isinstance(row, Mapping):
            raise CaperNativeKSeedPopulationError("source row differs")
        source_id = row.get("source_id")
        if not isinstance(source_id, str) or source_id in by_id:
            raise CaperNativeKSeedPopulationError("source ID differs")
        split = row.get("split")
        expected_split = (
            "fit" if source_id in FIT_SOURCE_IDS else "lockbox"
            if source_id in LOCKBOX_SOURCE_IDS
            else None
        )
        source_hw = row.get("source_hw")
        bucket_hw = row.get("bucket_hw")
        latent_shape = row.get("latent_shape")
        if (
            split != expected_split
            or not isinstance(row.get("identity_id"), str)
            or not isinstance(row.get("scene_id"), str)
            or row.get("registered_turn_target") not in {
                "frame_right",
                "frame_right_toward_background",
                "camera",
            }
            or not isinstance(row.get("source_video"), str)
            or not str(row["source_video"]).endswith(
                f"/samples/{source_id}/samples/{source_id}/source_video.mp4"
            )
            or _SHA256.fullmatch(str(row.get("source_video_sha256"))) is None
            or not isinstance(source_hw, list)
            or len(source_hw) != 2
            or not all(type(value) is int and value > 0 for value in source_hw)
            or not isinstance(bucket_hw, list)
            or len(bucket_hw) != 2
            or not all(type(value) is int and value % 16 == 0 for value in bucket_hw)
            or latent_shape
            != [1, 16, LATENT_PHASES, bucket_hw[0] // 8, bucket_hw[1] // 8]
            or _sha256_text(str(row.get("target_action_caption")))
            != row.get("target_action_caption_sha256")
        ):
            raise CaperNativeKSeedPopulationError(f"source {source_id!r} differs")
        caption = str(row["target_action_caption"])
        for phrase in (
            "From frames 0 through 20",
            "From frames 20 through 40",
            "From frames 40 through 80",
            "Preserve the source",
        ):
            if phrase not in caption:
                raise CaperNativeKSeedPopulationError(
                    f"source {source_id!r} phase caption differs"
                )
        by_id[source_id] = row
    if tuple(source_id for source_id in FIT_SOURCE_IDS if source_id in by_id) != FIT_SOURCE_IDS:
        raise CaperNativeKSeedPopulationError("fit source closure differs")
    if tuple(source_id for source_id in LOCKBOX_SOURCE_IDS if source_id in by_id) != LOCKBOX_SOURCE_IDS:
        raise CaperNativeKSeedPopulationError("lockbox source closure differs")
    return by_id


