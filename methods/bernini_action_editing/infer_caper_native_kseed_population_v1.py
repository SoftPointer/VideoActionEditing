def _canonical_registry() -> Mapping[str, Any]:
    path = METHOD_ROOT / CANONICAL_REGISTRY_RELATIVE
    if (
        not path.is_file()
        or path.is_symlink()
        or _file_sha256(path) != CANONICAL_REGISTRY_SHA256
    ):
        raise CaperNativeKSeedPopulationError("sealed K-seed registry bytes differ")
    try:
        value = json.loads(path.read_text(encoding="utf-8"))
    except Exception as error:
        raise CaperNativeKSeedPopulationError(
            "sealed K-seed registry JSON differs"
        ) from error
    if not isinstance(value, Mapping):
        raise CaperNativeKSeedPopulationError("registry root differs")
    return value


def _validate_action_taxonomy(registry: Mapping[str, Any]) -> None:
    taxonomy = registry.get("action_taxonomy")
    if not isinstance(taxonomy, Mapping):
        raise CaperNativeKSeedPopulationError("action taxonomy differs")
    unsigned = dict(taxonomy)
    declared = unsigned.pop("action_taxonomy_sha256", None)
    intervals = unsigned.get("event_frame_intervals_inclusive")
    if (
        taxonomy.get("action_family_id") != ACTION_FAMILY_ID
        or taxonomy.get("event_phase_order") != list(EVENT_PHASE_ORDER)
        or intervals
        != {
            "lower_hips_and_sit": [0, 20],
            "turn_head_to_registered_target": [20, 40],
            "stable_seated_hold": [40, 80],
        }
        or taxonomy.get("phase_boundary_overlap_is_intentional") is not True
        or declared != ACTION_TAXONOMY_SHA256
        or _object_sha256(unsigned) != declared
    ):
        raise CaperNativeKSeedPopulationError("action taxonomy seal differs")


