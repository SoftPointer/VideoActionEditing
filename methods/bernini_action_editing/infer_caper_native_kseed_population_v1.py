def _validate_registry(registry: Mapping[str, Any]) -> Mapping[str, Mapping[str, Any]]:
    canonical = _canonical_registry()
    if registry != canonical:
        raise CaperNativeKSeedPopulationError("registry differs from sealed authority")
    if (
        registry.get("schema_version") != REGISTRY_SCHEMA_VERSION
        or registry.get("method") != METHOD
    ):
        raise CaperNativeKSeedPopulationError("registry root differs")
    _validate_action_taxonomy(registry)
    _validate_native_contract(registry)
    _validate_population_design(registry)
    sources = _validate_sources(registry)
    _validate_posthoc_negative(registry)
    release = registry.get("lockbox_release_contract")
    if (
        not isinstance(release, Mapping)
        or release.get("schema_version") != THRESHOLD_FREEZE_SCHEMA_VERSION
        or release.get("fit_population_cell_ids_sha256") != FIT_CELL_IDS_SHA256
        or release.get("receipt_digest_required") is not True
    ):
        raise CaperNativeKSeedPopulationError("threshold-freeze contract differs")
    return sources


def _registry_cell(
    registry: Mapping[str, Any], *, cell_id: str, population_phase: str
) -> Mapping[str, Any]:
    sources = _validate_registry(registry)
    if population_phase not in PHASE_CELL_ORDER:
        raise CaperNativeKSeedPopulationError("population phase differs")
    if cell_id not in PHASE_CELL_ORDER[population_phase]:
        raise CaperNativeKSeedPopulationError("cell is outside the requested phase")
    for source_id in PHASE_SOURCE_IDS[population_phase]:
        for seed in PHASE_SEEDS[population_phase]:
            expected = f"{population_phase}-{source_id}-s{seed}"
            if expected == cell_id:
                return {
                    **dict(sources[source_id]),
                    "cell_id": cell_id,
                    "population_phase": population_phase,
                    "seed": seed,
                    "action_family_id": ACTION_FAMILY_ID,
                    "action_taxonomy_sha256": ACTION_TAXONOMY_SHA256,
                    "selected_before_generation": True,
                    "seed_filtering_or_best_of_k_authorized": False,
                }
    raise CaperNativeKSeedPopulationError("cell Cartesian coordinates differ")


def _validate_threshold_freeze_receipt(
    value: str | Path,
    *,
    expected_sha256: str,
    runtime_source_revision: str,
) -> Mapping[str, Any]:
    try:
        path, payload = _plain_json(value, label="threshold-freeze receipt")
    except Exception as error:
        raise CaperNativeKSeedPopulationError(str(error)) from error
    if (
        _SHA256.fullmatch(expected_sha256) is None
        or _file_sha256(path) != expected_sha256
    ):
        raise CaperNativeKSeedPopulationError("threshold-freeze file hash differs")
    required_fields = {
        "schema_version",
        "registry_sha256",
        "action_family_id",
        "action_taxonomy_sha256",
        "runtime_source_revision",
        "fit_population_complete",
        "fit_population_receipt_sha256",
        "fit_population_cell_ids_sha256",
        "reward_thresholds_sha256",
        "evaluation_protocol_sha256",
        "method_and_thresholds_frozen_before_lockbox",
        "lockbox_media_opened_before_freeze_is_false",
        "lockbox_generation_authorized",
        "receipt_digest",
    }
    if set(payload) != required_fields:
        raise CaperNativeKSeedPopulationError("threshold-freeze fields differ")
    unsigned = dict(payload)
    declared = unsigned.pop("receipt_digest", None)
    for key in (
        "registry_sha256",
        "action_taxonomy_sha256",
        "fit_population_receipt_sha256",
        "fit_population_cell_ids_sha256",
        "reward_thresholds_sha256",
        "evaluation_protocol_sha256",
        "receipt_digest",
    ):
        if _SHA256.fullmatch(str(payload.get(key))) is None:
            raise CaperNativeKSeedPopulationError(
                f"threshold-freeze {key} differs"
            )
    if (
        payload.get("schema_version") != THRESHOLD_FREEZE_SCHEMA_VERSION
        or payload.get("registry_sha256") != CANONICAL_REGISTRY_SHA256
        or payload.get("action_family_id") != ACTION_FAMILY_ID
        or payload.get("action_taxonomy_sha256") != ACTION_TAXONOMY_SHA256
        or payload.get("runtime_source_revision") != runtime_source_revision
        or payload.get("fit_population_complete") is not True
        or payload.get("fit_population_cell_ids_sha256") != FIT_CELL_IDS_SHA256
        or payload.get("method_and_thresholds_frozen_before_lockbox") is not True
        or payload.get("lockbox_media_opened_before_freeze_is_false") is not True
        or payload.get("lockbox_generation_authorized") is not True
        or _object_sha256(unsigned) != declared
    ):
        raise CaperNativeKSeedPopulationError("threshold-freeze seal differs")
    return {
        "path": str(path),
        "artifact_sha256": expected_sha256,
        "receipt_digest": declared,
        "fit_population_receipt_sha256": payload["fit_population_receipt_sha256"],
        "fit_population_cell_ids_sha256": payload["fit_population_cell_ids_sha256"],
        "reward_thresholds_sha256": payload["reward_thresholds_sha256"],
        "evaluation_protocol_sha256": payload["evaluation_protocol_sha256"],
        "runtime_source_revision": payload["runtime_source_revision"],
        "method_and_thresholds_frozen_before_lockbox": True,
        "lockbox_media_opened_before_freeze_is_false": True,
    }


