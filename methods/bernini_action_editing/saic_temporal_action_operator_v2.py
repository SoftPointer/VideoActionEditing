#!/usr/bin/env python3
"""Phase-routed Stage-B action operator for frozen Bernini-R 1.3B.

This replaces the exploratory discrete typed-arrow router with an online
representation generated by :mod:`saic_online_motion_field_v1`.  For each
target-row hidden state in blocks 0..22 cross-attention Q/O, the native target
token's exact81 latent phase selects one of the 21 frozen 32-D motion codes::

    delta(h_i) = up(silu(state_down(h_i)) * tanh(phase_gate(code[phase(i)])))

All learned maps are bias-free FP32 rank 8 and ``up`` is zero initialized.
Thus installation is byte-exact and the only trainable parameters are the
registered ``attn2.to_q`` / ``attn2.to_out[0]`` maps.  Native source-video,
reference, and append-padding rows are never changed.  Exact40 indices 38/39
and exact-zero online no-op codes return the frozen projection directly,
without evaluating the learned path.

The route is minted from the already-built native V/VI branch, audited live
UniPC scheduler/timestep, Bernini's live Ulysses state, and the exact current
noisy target object used to build the online field.  Callers cannot report a
mask, rank, SP size, schedule index, sigma, phase map, action ID, or phase
code.  Training and inference therefore enter precisely the same route.
"""

